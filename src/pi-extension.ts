import { execFileSync } from "node:child_process";
import path from "node:path";
import { Type } from "@earendil-works/pi-ai";
import { defineTool, type ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { RepoGraph } from "./db.js";
import { indexRepo } from "./indexer/index.js";
import { ingestGit } from "./git.js";
import {
  addLesson,
  claimFile,
  endSession,
  impact,
  inbox,
  knownProcedures,
  recordCommand,
  recordFileEvent,
  renderImpact,
  startSession,
} from "./memory.js";
import { buildPack, renderPack } from "./pack.js";
import { repoSlug } from "./repo.js";
import { findSymbols, renderFind } from "./lookup.js";

export interface EngramOptions {
  /** Agent identity used for claims and episodic memory. Default: $ENGRAM_AGENT or pi-<pid>. */
  agent?: string;
  /** Token budget of the injected context pack. */
  budget?: number;
  /** Inject the pack automatically before every prompt (the point of Engram). */
  autoPack?: boolean;
  /** Register the graph tools (find / impact / remember). */
  tools?: boolean;
  /** Called with the graph session id whenever a run starts (benchmarks use it to record outcomes). */
  onSession?: (id: string) => void;
  /** Reuse a parent's session (subagents). */
  parentSession?: string;
  /** Repository root and graph slug (default: git root of cwd, slug from origin remote). */
  root?: string;
  repo?: string;
}

function gitRoot(cwd: string) {
  try {
    return execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return cwd;
  }
}

export function createEngramExtension(opts: EngramOptions = {}) {
  return function engram(pi: ExtensionAPI) {
    const agent = opts.agent ?? process.env.ENGRAM_AGENT ?? `pi-${process.pid}`;
    let g: RepoGraph | undefined;
    let root = "";
    let sessionId: string | undefined;
    let runStart = 0;
    let lastVerifyOk: boolean | undefined;
    let edited = false;

    const rel = (p: unknown) => {
      if (typeof p !== "string" || !p) return undefined;
      const abs = path.isAbsolute(p) ? p : path.join(root, p);
      const r = path.relative(root, abs);
      return r.startsWith("..") ? undefined : r.split(path.sep).join("/");
    };

    async function ready() {
      if (g) return g;
      root = opts.root ?? gitRoot(process.cwd());
      g = await RepoGraph.open(opts.repo ?? repoSlug(root));
      const s = await indexRepo(g, root); // incremental: only changed files are re-parsed
      if (s.changed === s.files) await ingestGit(g, root); // first time we see this repo
      return g;
    }

    pi.on("session_start", async (_e, ctx) => {
      try {
        await ready();
        if (ctx.hasUI) ctx.ui.setStatus?.("engram", `engram: ${g!.repo}`);
      } catch (err) {
        if (ctx.hasUI) ctx.ui.notify(`engram: graph unavailable (${(err as Error).message})`, "warning");
      }
    });

    pi.on("before_agent_start", async (event) => {
      if (event.messageType !== "user" || !event.prompt.trim()) return;
      const graph = await ready();
      runStart = Date.now();
      lastVerifyOk = undefined;
      edited = false;
      const pack = opts.autoPack === false ? undefined : await buildPack(graph, root, event.prompt, { budget: opts.budget ?? 2000 });
      sessionId = await startSession(graph, { agent, task: event.prompt.slice(0, 500) }, pack);
      opts.onSession?.(sessionId);
      if (!pack) return;

      const extras: string[] = [];
      const procs = await knownProcedures(graph);
      if (procs.length) extras.push(`### How to verify in this repo (worked before)\n${procs.map((p) => `- \`${p.cmd}\` (${p.ok}× ok)`).join("\n")}`);
      if (opts.parentSession) {
        const notes = await inbox(graph, sessionId);
        if (notes.length) extras.push(`### Handoff notes\n${notes.map((n) => `- ${n.note}`).join("\n")}`);
      }
      return {
        message: {
          customType: "engram-pack",
          content: [renderPack(pack), ...extras].join("\n\n"),
          display: true,
          details: { tokens: pack.tokens, items: pack.items.length, ms: pack.ms },
        },
      };
    });

    pi.on("tool_call", async (event) => {
      if (!g || !sessionId) return;
      if (event.toolName === "edit" || event.toolName === "write") {
        const file = rel((event.input as { path?: string }).path);
        if (!file) return;
        const claim = await claimFile(g, sessionId, agent, file, "edit");
        if (!claim.ok) {
          return {
            block: true,
            reason: `${file} is being edited by ${claim.holder!.agent} (session task: "${claim.holder!.intent}"). Work on something else or wait; do not edit this file now.`,
          };
        }
      }
      return;
    });

    pi.on("tool_result", async (event) => {
      if (!g || !sessionId) return;
      const input = event.input as { path?: string; command?: string };
      const name = (event as { toolName?: string }).toolName;
      try {
        if (name === "read") {
          const file = rel(input.path);
          if (file) await recordFileEvent(g, sessionId, file, "READ");
        } else if ((name === "edit" || name === "write") && !event.isError) {
          const file = rel(input.path);
          if (file) {
            edited = true;
            await indexRepo(g, root, [file]); // keep the graph current while the agent works
            await recordFileEvent(g, sessionId, file, "EDITED");
          }
        } else if (name === "bash" && input.command) {
          await recordCommand(g, sessionId, input.command, !event.isError);
          if (/\b(pytest|test|vitest|jest)\b/.test(input.command)) lastVerifyOk = !event.isError;
        }
      } catch {
        /* memory is best-effort; never break the agent's tool call */
      }
      return;
    });

    pi.on("agent_end", async (event) => {
      if (!g || !sessionId) return;
      let tin = 0;
      let tout = 0;
      let calls = 0;
      for (const m of event.messages as Array<{ role: string; usage?: { input: number; output: number; cacheRead: number; cacheWrite: number }; content?: Array<{ type: string }> }>) {
        if (m.role !== "assistant") continue;
        tin += (m.usage?.input ?? 0) + (m.usage?.cacheRead ?? 0) + (m.usage?.cacheWrite ?? 0);
        tout += m.usage?.output ?? 0;
        calls += m.content?.filter((c) => c.type === "toolCall").length ?? 0;
      }
      const outcome = lastVerifyOk === true && edited ? "success" : lastVerifyOk === false ? "failure" : "unknown";
      await endSession(g, sessionId, { outcome, tokensIn: tin, tokensOut: tout, toolCalls: calls, durationMs: Date.now() - runStart });
    });

    if (opts.tools === false) return;

    pi.registerTool(
      defineTool({
        name: "engram_find",
        label: "Engram find",
        description: "Find where a function/class/method is defined, with its callers and callees, from the code graph. Faster and cheaper than grep for symbol lookups.",
        parameters: Type.Object({ name: Type.String({ description: "Symbol name, e.g. get_default or Option.get_default" }) }),
        async execute(_id, params) {
          const graph = await ready();
          const rows = await findSymbols(graph, params.name);
          return { content: [{ type: "text", text: renderFind(rows) }], details: { count: rows.length } };
        },
      }),
    );
    pi.registerTool(
      defineTool({
        name: "engram_impact",
        label: "Engram impact",
        description: "Blast radius of changing a file or symbol (path or path#Qual.name): transitive callers, tests that reach it, files usually changed with it, lessons.",
        parameters: Type.Object({ target: Type.String({ description: "e.g. src/pkg/core.py or src/pkg/core.py#Option.get_default" }) }),
        async execute(_id, params) {
          const graph = await ready();
          return { content: [{ type: "text", text: renderImpact(await impact(graph, params.target)) }], details: undefined };
        },
      }),
    );
    pi.registerTool(
      defineTool({
        name: "engram_remember",
        label: "Engram remember",
        description: "Save a short lesson future sessions should know (a pitfall, invariant, or non-obvious fix), attached to a file or symbol.",
        parameters: Type.Object({
          lesson: Type.String({ description: "One sentence" }),
          about: Type.Optional(Type.String({ description: "File path or path#Qual.name" })),
        }),
        async execute(_id, params) {
          const graph = await ready();
          await addLesson(graph, sessionId, params.lesson, params.about);
          return { content: [{ type: "text", text: "saved" }], details: undefined };
        },
      }),
    );
  };
}

export default createEngramExtension();
