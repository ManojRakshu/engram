import { RepoGraph, close, latencyStats } from "../src/db.ts";
import * as m from "../src/memory.ts";
const g = await RepoGraph.open("pallets-click");
const a = await m.startSession(g, { agent: "agent-A", task: "fix default conversion for multiple options" });
const b = await m.startSession(g, { agent: "agent-B", task: "refactor option help text" });
console.log("A claims core.py:", await m.claimFile(g, a, "agent-A", "src/click/core.py", "fix get_default"));
console.log("B claims core.py:", await m.claimFile(g, b, "agent-B", "src/click/core.py", "help text"));
console.log("B claims types.py:", await m.claimFile(g, b, "agent-B", "src/click/types.py"));
console.log("active:", await m.activeClaims(g));
await m.recordFileEvent(g, a, "src/click/core.py", "READ");
await m.recordFileEvent(g, a, "src/click/core.py", "EDITED");
await m.addLesson(g, a, "Option.get_default must cast multiple=True defaults through type_cast_value", "src/click/core.py");
await m.recordCommand(g, a, "cd /x && python -m pytest tests/test_defaults.py::test_multiple -q", true);
await m.endSession(g, a, { outcome: "success", tokensIn: 1000, tokensOut: 100, toolCalls: 5 });
console.log("B claims core.py after A ended:", await m.claimFile(g, b, "agent-B", "src/click/core.py"));
await m.handoff(g, a, b, "default casting fixed; help text for multiple still says [default: None]");
console.log("B inbox:", await m.inbox(g, b));
console.log("procedures:", await m.knownProcedures(g));
console.log(m.renderImpact(await m.impact(g, "src/click/core.py#Option.get_default")));
console.log(latencyStats());
await close();
